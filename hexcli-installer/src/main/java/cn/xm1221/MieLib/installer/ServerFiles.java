package cn.xm1221.MieLib.installer;

import java.nio.file.Path;

/**
 * Writes the files that turn a directory into a runnable HexCLI server:
 * {@code eula.txt}, {@code server.properties}, {@code java-path.txt} and the launch scripts.
 *
 * <p>User-owned files are never overwritten: {@code eula.txt} and {@code server.properties} are
 * only written when absent. Generated scripts are rewritten so a re-run picks up installer fixes.
 */
final class ServerFiles {
    private final String version;

    ServerFiles(String version) {
        this.version = version;
    }

    /** Writes {@code eula.txt} if absent. Returns {@code true} when the file was created. */
    boolean writeEula(Path dir) {
        return Fs.writeIfAbsent(dir.resolve("eula.txt"),
            "# Accepted via the HexCLI installer; see https://aka.ms/MinecraftEULA\n"
                + "eula=true\n");
    }

    /** Writes a minimal offline {@code server.properties} if absent. */
    boolean writeServerProperties(Path dir) {
        // Only the keys HexCLI needs. Minecraft fills in every other default on first start.
        String properties = """
            # Generated by the HexCLI installer; edit freely, this file is never overwritten.
            online-mode=false
            server-ip=127.0.0.1
            server-port=25565
            spawn-protection=0
            motd=HexCLI
            enable-rcon=false
            """;
        return Fs.writeIfAbsent(dir.resolve("server.properties"), properties);
    }

    /** Remembers the Java executable used for the install, for scripts when no private runtime is found. */
    void writeJavaPath(Path dir, String javaExecutable) {
        if (javaExecutable == null || javaExecutable.isBlank()) {
            return;
        }
        Fs.write(dir.resolve("java-path.txt"), javaExecutable + System.lineSeparator());
    }

    void writeScripts(Path dir) {
        Fs.writeExecutable(dir.resolve("start-server.sh"), startServerSh());
        Fs.writeExecutable(dir.resolve("connect.sh"), connectSh());
        Fs.writeExecutable(dir.resolve("start-and-connect.sh"), startAndConnectSh());
        // cmd.exe is happiest with CRLF; LF-only batch files can mis-parse labels and gotos.
        Fs.write(dir.resolve("start-server.bat"), crlf(startServerBat()));
        Fs.write(dir.resolve("connect.bat"), crlf(connectBat()));
        Fs.write(dir.resolve("start-and-connect.bat"), crlf(startAndConnectBat()));
    }

    private static String crlf(String text) {
        return text.replace("\r\n", "\n").replace("\n", "\r\n");
    }

    // ---- POSIX sh ----

    /**
     * Java lookup shared by the Unix scripts. {@code DIR} is the server directory, {@code ROOT} its
     * parent (the extracted archive root, which holds {@code runtime/}). The private runtime wins over
     * the system Java; {@code HEXCLI_JAVA} overrides everything. Nothing here touches PATH.
     */
    private static final String FIND_JAVA_SH = """
        find_java() {
            if [ -n "${HEXCLI_JAVA:-}" ] && [ -x "${HEXCLI_JAVA}" ]; then
                printf '%s\\n' "$HEXCLI_JAVA"
                return 0
            fi
            # Private runtime: Linux/Windows layout, then the macOS Contents/Home layout.
            for candidate in \\
                "$ROOT/runtime/bin/java" \\
                "$ROOT/runtime/Contents/Home/bin/java" \\
                "$ROOT"/runtime/*/Contents/Home/bin/java \\
                "$ROOT"/runtime/*/bin/java; do
                if [ -x "$candidate" ]; then
                    printf '%s\\n' "$candidate"
                    return 0
                fi
            done
            if [ -f "$DIR/java-path.txt" ]; then
                candidate=$(sed -n '1p' "$DIR/java-path.txt" 2>/dev/null || true)
                if [ -n "$candidate" ] && [ -x "$candidate" ]; then
                    printf '%s\\n' "$candidate"
                    return 0
                fi
            fi
            if [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/java" ]; then
                printf '%s\\n' "$JAVA_HOME/bin/java"
                return 0
            fi
            if command -v java >/dev/null 2>&1; then
                command -v java
                return 0
            fi
            return 1
        }

        require_java() {
            JAVA=$(find_java) || {
                echo "error: no Java 17+ found." >&2
                echo "       Put a private runtime in $ROOT/runtime, set HEXCLI_JAVA=/path/to/java," >&2
                echo "       or set JAVA_HOME." >&2
                exit 1
            }
        }
        """;

    private String startServerSh() {
        return """
            #!/bin/sh
            # HexCLI server launcher - generated by hexcli-installer @VERSION@.
            # Re-run the installer to regenerate (eula.txt / server.properties are left alone).
            set -eu
            DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
            ROOT=$(dirname -- "$DIR")
            @FIND_JAVA@
            require_java
            cd "$DIR"
            exec "$JAVA" -Xmx2G -Dmielib.hexcli=true -jar "$DIR/fabric-server-launch.jar" nogui "$@"
            """.replace("@VERSION@", version).replace("@FIND_JAVA@", FIND_JAVA_SH);
    }

    private String connectSh() {
        return """
            #!/bin/sh
            # HexCLI terminal client - generated by hexcli-installer @VERSION@.
            set -eu
            DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
            ROOT=$(dirname -- "$DIR")
            @FIND_JAVA@
            require_java
            CLIENT="$DIR/hexcli-client.jar"
            if [ ! -f "$CLIENT" ]; then
                if [ -f "$ROOT/hexcli-client.jar" ]; then
                    CLIENT="$ROOT/hexcli-client.jar"
                else
                    echo "error: hexcli-client.jar not found in $DIR or $ROOT." >&2
                    echo "       Re-run the installer with --client-jar <path>." >&2
                    exit 1
                fi
            fi
            exec "$JAVA" -jar "$CLIENT" --dir "$DIR" "$@"
            """.replace("@VERSION@", version).replace("@FIND_JAVA@", FIND_JAVA_SH);
    }

    private String startAndConnectSh() {
        return """
            #!/bin/sh
            # Start the HexCLI server, wait for hexcli/client.json, run the client, then stop the server.
            # Generated by hexcli-installer @VERSION@.
            set -eu
            DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
            ROOT=$(dirname -- "$DIR")
            @FIND_JAVA@
            require_java

            LOG="$DIR/logs/hexcli-console.log"
            FIFO="$DIR/.hexcli-server-stdin"
            SERVER_PID=""
            mkdir -p "$DIR/logs"
            rm -f "$FIFO"
            mkfifo "$FIFO"

            cleanup() {
                if [ -n "$SERVER_PID" ] && kill -0 "$SERVER_PID" 2>/dev/null; then
                    printf 'stop\\n' >&3 2>/dev/null || true
                    waited=0
                    while kill -0 "$SERVER_PID" 2>/dev/null && [ "$waited" -lt 60 ]; do
                        sleep 1
                        waited=$((waited + 1))
                    done
                    kill "$SERVER_PID" 2>/dev/null || true
                fi
                exec 3>&- 2>/dev/null || true
                rm -f "$FIFO"
            }
            trap cleanup EXIT
            trap 'exit 130' INT TERM

            cd "$DIR"
            # The server's stdin is a FIFO so cleanup() can send "stop" for a clean shutdown.
            "$JAVA" -Xmx2G -Dmielib.hexcli=true -jar "$DIR/fabric-server-launch.jar" nogui \\
                <"$FIFO" >"$LOG" 2>&1 &
            SERVER_PID=$!
            exec 3>"$FIFO"

            echo "server started (pid $SERVER_PID); console log: $LOG"
            CLIENT_JSON="$DIR/hexcli/client.json"
            waited=0
            while [ ! -f "$CLIENT_JSON" ]; do
                if ! kill -0 "$SERVER_PID" 2>/dev/null; then
                    echo "error: the server exited during startup; last log lines:" >&2
                    tail -n 40 "$LOG" >&2 || true
                    exit 1
                fi
                if [ "$waited" -ge 300 ]; then
                    echo "error: timed out after 300s waiting for $CLIENT_JSON" >&2
                    echo "       (the first start downloads the vanilla server from Mojang)" >&2
                    exit 1
                fi
                sleep 1
                waited=$((waited + 1))
            done

            echo "server ready; starting the HexCLI client (quit / Ctrl-D stops the server)"
            status=0
            "$JAVA" -jar "$DIR/hexcli-client.jar" --dir "$DIR" "$@" || status=$?
            exit "$status"
            """.replace("@VERSION@", version).replace("@FIND_JAVA@", FIND_JAVA_SH);
    }

    // ---- Windows batch ----

    /**
     * Java lookup for batch scripts. Kept as a subroutine because each line of a batch file is
     * parsed when it runs, so {@code %JAVA%} must be read on its own line after it is set.
     */
    private static final String FIND_JAVA_BAT = """
        rem Find Java: HEXCLI_JAVA > private runtime > java-path.txt > JAVA_HOME > PATH.
        :find_java
        set "JAVA="
        if defined HEXCLI_JAVA if exist "%HEXCLI_JAVA%" set "JAVA=%HEXCLI_JAVA%"
        if not defined JAVA if exist "%ROOT%\\runtime\\bin\\java.exe" set "JAVA=%ROOT%\\runtime\\bin\\java.exe"
        if not defined JAVA if exist "%DIR%java-path.txt" call :read_java_path
        if not defined JAVA if defined JAVA_HOME if exist "%JAVA_HOME%\\bin\\java.exe" set "JAVA=%JAVA_HOME%\\bin\\java.exe"
        if not defined JAVA for %%j in (java.exe) do set "JAVA=%%~$PATH:j"
        if not defined JAVA (
            echo error: no Java 17+ found. Put a private runtime in "%ROOT%\\runtime", 1>&2
            echo        set HEXCLI_JAVA to a java.exe, or set JAVA_HOME. 1>&2
            exit /b 1
        )
        exit /b 0

        :read_java_path
        set /p JAVA=<"%DIR%java-path.txt"
        if not exist "%JAVA%" set "JAVA="
        exit /b 0
        """;

    private String startServerBat() {
        return """
            @echo off
            rem HexCLI server launcher - generated by hexcli-installer @VERSION@.
            rem Re-run the installer to regenerate (eula.txt / server.properties are left alone).
            setlocal EnableExtensions
            set "DIR=%~dp0"
            for %%i in ("%DIR%..") do set "ROOT=%%~fi"
            call :find_java
            if errorlevel 1 exit /b 1
            cd /d "%DIR%"
            "%JAVA%" -Xmx2G -Dmielib.hexcli=true -jar "%DIR%fabric-server-launch.jar" nogui %*
            exit /b %ERRORLEVEL%

            @FIND_JAVA@
            """.replace("@VERSION@", version).replace("@FIND_JAVA@", FIND_JAVA_BAT);
    }

    private String connectBat() {
        return """
            @echo off
            rem HexCLI terminal client - generated by hexcli-installer @VERSION@.
            setlocal EnableExtensions
            set "DIR=%~dp0"
            for %%i in ("%DIR%..") do set "ROOT=%%~fi"
            call :find_java
            if errorlevel 1 exit /b 1
            set "CLIENT=%DIR%hexcli-client.jar"
            if not exist "%CLIENT%" if exist "%ROOT%\\hexcli-client.jar" set "CLIENT=%ROOT%\\hexcli-client.jar"
            if not exist "%CLIENT%" (
                echo error: hexcli-client.jar not found in "%DIR%" or "%ROOT%". 1>&2
                echo        Re-run the installer with --client-jar ^<path^>. 1>&2
                exit /b 1
            )
            "%JAVA%" -jar "%CLIENT%" --dir "%DIR%" %*
            exit /b %ERRORLEVEL%

            @FIND_JAVA@
            """.replace("@VERSION@", version).replace("@FIND_JAVA@", FIND_JAVA_BAT);
    }

    private String startAndConnectBat() {
        return """
            @echo off
            rem Start the HexCLI server, wait for hexcli\\client.json, run the client, then stop the server.
            rem Generated by hexcli-installer @VERSION@.
            rem
            rem NOTE: Windows has no easy way to write to a detached process's stdin, so unlike the
            rem       Unix script this stops the server by terminating the process. Minecraft saves
            rem       periodically; use start-server.bat + connect.bat if you need a clean "stop".
            setlocal EnableExtensions
            set "DIR=%~dp0"
            for %%i in ("%DIR%..") do set "ROOT=%%~fi"
            call :find_java
            if errorlevel 1 exit /b 1

            if not exist "%DIR%logs" mkdir "%DIR%logs"
            set "SERVER_PID="
            rem Start-Process joins -ArgumentList with spaces without quoting, so the jar is passed as a
            rem bare name and -WorkingDirectory points at the server dir (paths with spaces are fine).
            for /f "usebackq delims=" %%p in (`powershell -NoProfile -Command "$p = Start-Process -FilePath '%JAVA%' -ArgumentList '-Xmx2G','-Dmielib.hexcli=true','-jar','fabric-server-launch.jar','nogui' -WorkingDirectory '%DIR%' -WindowStyle Minimized -PassThru; $p.Id"`) do set "SERVER_PID=%%p"
            if not defined SERVER_PID (
                echo error: could not start the server. 1>&2
                exit /b 1
            )
            echo server started (pid %SERVER_PID%); waiting for hexcli\\client.json ...

            rem Non-zero so the error paths below cannot fall through as success.
            set "STATUS=1"
            set /a WAITED=0
            :wait_for_client
            if exist "%DIR%hexcli\\client.json" goto server_ready
            tasklist /FI "PID eq %SERVER_PID%" 2>nul | find "%SERVER_PID%" >nul
            if errorlevel 1 (
                echo error: the server exited during startup. 1>&2
                goto stop_server
            )
            if %WAITED% GEQ 300 (
                echo error: timed out after 300s waiting for "%DIR%hexcli\\client.json". 1>&2
                echo        ^(the first start downloads the vanilla server from Mojang^) 1>&2
                goto stop_server
            )
            timeout /t 1 /nobreak >nul
            set /a WAITED+=1
            goto wait_for_client

            :server_ready
            echo server ready; starting the HexCLI client ^(quit / Ctrl-D stops the server^)
            set "STATUS=0"
            "%JAVA%" -jar "%DIR%hexcli-client.jar" --dir "%DIR%" %*
            set "STATUS=%ERRORLEVEL%"

            :stop_server
            echo stopping the server ...
            powershell -NoProfile -Command "Stop-Process -Id %SERVER_PID% -Force -ErrorAction SilentlyContinue" >nul 2>&1
            exit /b %STATUS%

            @FIND_JAVA@
            """.replace("@VERSION@", version).replace("@FIND_JAVA@", FIND_JAVA_BAT);
    }
}
