}

val hexNeoForgeJar = rootProject.file("libs/hexcasting-neoforge-1.21.1-0.12.0-devel-pre-64.jar")

dependencies {
    neoForge(libs.neoforge)
    implementation(libs.architectury.neoforge)

    // KFF is the runtime Kotlin loader. Sources are compiled by this project's Kotlin plugin.
    modImplementation(libs.kotlin.neoforge) {
        exclude(group = "net.neoforged.fancymodloader", module = "loader")
    }

    // BlameJared has no Hex Casting 1.21 artifacts. This jar is Mojmap (named), same bytes as
    // MieHexRevolution's 1.21 common/libs copy of 0.12.0-devel-pre-64.
    implementation(files(hexNeoForgeJar))

    modImplementation(libs.paucal.neoforge)
    modLocalRuntime(libs.patchouli.neoforge)
    modLocalRuntime(libs.caelus)
    modLocalRuntime(libs.inline.neoforge) { isTransitive = false }

    modApi(libs.clothConfig.neoforge)

    libs.mixinExtras.common.also {
        compileOnly(it)
        annotationProcessor(it)
    }
}

tasks {
    // The common refmap is generated by the legacy mixin AP with intermediary (Fabric) names,
    // e.g. GuiSpellcasting.render -> method_25394. NeoForge runs on Mojmap, which is exactly what
    // the mixin sources already say, so the NeoForge jar must ship no refmap at all. Shipping the
    // intermediary one crashes the client ("could not find any targets matching ...method_25394").
    processResources {
        filesMatching("mielib-common.mixins.json") {
            filter { line -> if (line.trimStart().startsWith("\"refmap\"")) "" else line }
        }
    }

    shadowJar {
        exclude("fabric.mod.json")
        exclude("mielib-common.refmap.json")
    }

    // Fail the build instead of the client if an intermediary refmap ever sneaks back in.
    remapJar {
        doLast {
            val jar = archiveFile.get().asFile
            ZipFile(jar).use { zip ->
                check(zip.getEntry("mielib-common.refmap.json") == null) {
                    "$jar must not contain mielib-common.refmap.json (intermediary names break NeoForge)"
                }
                val cfg = zip.getInputStream(zip.getEntry("mielib-common.mixins.json")).reader().readText()
                check("\"refmap\"" !in cfg) { "$jar: mielib-common.mixins.json must not declare a refmap on NeoForge" }
            }
        }
    }
}

